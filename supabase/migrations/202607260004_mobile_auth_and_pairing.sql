-- Generate the QR JSON payload the Developer Portal encodes into a QR image
create or replace function public.generate_pairing_qr_payload(
    p_backend_url   text,
    p_ws_url        text,
    p_tenant_id     text default 'TENANT_FUZEN_001',
    p_created_by    uuid default null
)
returns jsonb
language plpgsql security definer as $$
declare
    v_pair_id           text := 'PAIR_' || upper(encode(gen_random_bytes(8), 'hex'));
    v_bootstrap_token   text := encode(gen_random_bytes(32), 'hex');
    v_expires_at        timestamptz := timezone('utc', now()) + interval '15 minutes';
begin
    insert into public.qr_pairing_sessions (
        pair_id, bootstrap_token, tenant_id,
        backend_url, ws_url,
        created_by_user_id, expires_at
    ) values (
        v_pair_id, v_bootstrap_token, p_tenant_id,
        p_backend_url, p_ws_url,
        p_created_by, v_expires_at
    );

    return jsonb_build_object(
        'backend',          p_backend_url,
        'ws',               p_ws_url,
        'pairId',           v_pair_id,
        'bootstrapToken',   v_bootstrap_token,
        'tenantId',         p_tenant_id,
        'expires',          v_expires_at
    );
end;
$$;

-- Cleanup expired tokens — call periodically via pg_cron or backend cron job
create or replace function public.cleanup_expired_auth_tokens()
returns integer
language plpgsql security definer as $$
declare
    v_count integer := 0;
begin
    -- Expire QR pairing sessions
    update public.qr_pairing_sessions
       set status = 'EXPIRED', updated_at = timezone('utc', now())
     where status = 'PENDING' and expires_at < timezone('utc', now());
    get diagnostics v_count = row_count;

    -- Expire password reset tokens
    update public.password_reset_tokens
       set status = 'EXPIRED', updated_at = timezone('utc', now())
     where status = 'PENDING' and expires_at < timezone('utc', now());

    -- Expire email verification tokens
    update public.email_verification_tokens
       set status = 'EXPIRED', updated_at = timezone('utc', now())
     where status = 'PENDING' and expires_at < timezone('utc', now());

    -- Revoke expired mobile app sessions
    update public.mobile_app_sessions
       set status = 'EXPIRED', updated_at = timezone('utc', now())
     where status = 'ACTIVE' and expires_at < timezone('utc', now());

    return v_count;
end;
$$;

