-- ─────────────────────────────────────────────────────────────────────────────
-- 1. QR PAIRING SESSIONS
--    Generated by Developer Portal when a user clicks "Generate Pairing QR".
--    The APK scans this, calls /api/sdk/pair, and the token is consumed.
-- ─────────────────────────────────────────────────────────────────────────────
create table if not exists public.qr_pairing_sessions (
    id                  uuid        primary key default gen_random_uuid(),
    pair_id             text        not null unique,                -- embedded in QR payload
    bootstrap_token     text        not null unique,               -- one-time bearer token for pairing
    tenant_id           text        not null default 'TENANT_FUZEN_001',
    app_id              text        not null default 'com.fusionbank.mobileapp',
    backend_url         text        not null,                      -- https://… URL given to APK
    ws_url              text        not null,                      -- wss://… URL given to APK
    created_by_user_id  uuid        references auth.users(id) on delete set null,
    device_uuid         text,                                      -- filled in after APK completes pairing
    paired_at           timestamptz,
    status              text        not null default 'PENDING'
                            check (status in ('PENDING','CONSUMED','EXPIRED','REVOKED')),
    expires_at          timestamptz not null default (timezone('utc', now()) + interval '15 minutes'),
    created_at          timestamptz not null default timezone('utc', now()),
    updated_at          timestamptz not null default timezone('utc', now())
);

create index if not exists idx_qr_pairing_pair_id      on public.qr_pairing_sessions (pair_id);
create index if not exists idx_qr_pairing_bootstrap    on public.qr_pairing_sessions (bootstrap_token);
create index if not exists idx_qr_pairing_status       on public.qr_pairing_sessions (status);
create index if not exists idx_qr_pairing_expires_at   on public.qr_pairing_sessions (expires_at);

create trigger qr_pairing_sessions_updated_at
    before update on public.qr_pairing_sessions
    for each row execute function public.set_updated_at();

